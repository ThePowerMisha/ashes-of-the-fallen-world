SUPPLIES = (
    'field_kit', 'scout_report', 'repair_kit', 'ward_charm',
    'cleansing_charge', 'foundation_stone', 'power_regulator', 'source_capacitor',
)


def decorate_quest(quest, chapter, order, position, rows, uid):
    art, dispatch = DISPATCHES[order]
    task = quest['tasks'][0]
    if position == 0:
        quest['description'].extend(['', f'Из записей экспедиции. {dispatch}', '',
            f'{{image:kubejs:textures/quest/{art}.png width:150 height:84 align:1}}'])
    if task['type'] == 'checkmark':
        quest['description'].append('После выполнения отметь задание вручную.')
    elif task['type'] == 'advancement':
        quest['description'].append('Квест засчитается автоматически при получении достижения.')

    # Keep the original reward ID so old completion and claimed reward data still applies.
    base = f'{chapter}/{position}/reward'
    targets = {row[1] for row in rows}
    item, count, experience = reward_terms(chapter, order, position, rows, quest)
    rewards = [{'id': uid(base), 'type': 'item', 'item': item, 'count': count}]
    if experience:
        rewards.append({'id': uid(base + '/experience'), 'type': 'xp', 'xp': experience})
    if position == len(rows) - 1 and order >= 8:
        candidates = ['kubejs:' + name for name in SUPPLIES if 'kubejs:' + name not in targets]
        rewards.append({'id': uid(base + '/supply'), 'type': 'item',
                        'item': candidates[order % len(candidates)], 'count': 1})
    quest['rewards'] = rewards
